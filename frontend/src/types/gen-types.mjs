/**
 * Generate `src/types/generated.ts` from the contract JSON Schemas in `../schemas`.
 *
 * Behavior:
 *     Merges every schema file and its `$defs` into one root `$defs` map, so each
 *     contract is emitted exactly once. Property-level `title` keys are removed so
 *     the compiler does not emit an alias type per field. All references already
 *     point at `#/$defs/<Name>`, so they resolve against the merged root. Keys
 *     beside a `$ref` are dropped, and `maxItems` does not expand into tuples.
 * Exceptions:
 *     Error: two schemas define the same name with different content.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const schemaDir = join(here, '..', '..', '..', 'schemas')
const outFile = join(here, 'generated.ts')

function stripTitles(node, keepTitle) {
  if (Array.isArray(node)) return node.map((item) => stripTitles(item, false))
  if (node === null || typeof node !== 'object') return node
  // Siblings of `$ref` (e.g. `default`) make the compiler emit a duplicate `Name1` type.
  if (typeof node.$ref === 'string') return { $ref: node.$ref }
  const out = {}
  for (const [key, value] of Object.entries(node)) {
    if (key === 'title' && !keepTitle) continue
    if (key === 'properties' || key === '$defs') {
      out[key] = Object.fromEntries(
        Object.entries(value).map(([name, sub]) => [name, stripTitles(sub, key === '$defs')]),
      )
    } else {
      out[key] = stripTitles(value, false)
    }
  }
  return out
}

const defs = {}
function addDef(name, schema) {
  const clean = stripTitles({ ...schema, title: name }, true)
  delete clean.$defs
  const existing = defs[name]
  if (existing && JSON.stringify(existing) !== JSON.stringify(clean)) {
    throw new Error(`conflicting definitions for ${name}`)
  }
  defs[name] = clean
}

const files = readdirSync(schemaDir).filter((f) => f.endsWith('.json')).sort()
for (const file of files) {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), 'utf8'))
  for (const [name, sub] of Object.entries(schema.$defs ?? {})) addDef(name, sub)
  addDef(schema.title ?? file.replace(/\.json$/, ''), schema)
}

const root = {
  title: 'PamContracts',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(defs).sort().map((n) => [n, { $ref: `#/$defs/${n}` }])),
  $defs: defs,
}

const ts = await compile(root, 'PamContracts', {
  bannerComment:
    '/* Generated by `npm run gen:types` from ../schemas/*.json. Do not edit by hand. */',
  additionalProperties: false,
  unreachableDefinitions: true,
  declareExternallyReferenced: true,
  format: true,
  maxItems: -1,
  style: { singleQuote: true, semi: false },
})
writeFileSync(outFile, ts)
console.log(`wrote ${outFile} (${Object.keys(defs).length} types from ${files.length} files)`)
